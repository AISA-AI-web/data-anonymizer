const num = (n: number) => n.toLocaleString('ar-u-nu-latn');

/** Keeps a left-to-right snippet (file extension, code, [NAME]) intact inside right-to-left text. */
const ltr = (s: string) => `⁦${s}⁩`;
/** Keeps text of unknown direction (a column heading or file name from the user's data) intact. */
const iso = (s: string) => `⁨${s}⁩`;
const quoted = (s: string) => `«${iso(s)}»`;

/** Forms of a counted noun. "#" is replaced with the number. */
interface Counted {
  one: string;
  two: string;
  /** 3–10 */
  few: string;
  /** 11–99 */
  many: string;
  /** 100 and above */
  other: string;
}

const pluralRules = new Intl.PluralRules('ar');

function count(n: number, forms: Counted): string {
  const rule = pluralRules.select(n);
  const form = rule === 'zero' ? forms.few : forms[rule as keyof Counted];
  return form.replace('#', num(n));
}

